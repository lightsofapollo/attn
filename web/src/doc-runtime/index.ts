function selectionIsLive(): boolean {
  const selection = window.getSelection();
  return !!selection && !selection.isCollapsed && selection.rangeCount > 0;
}

function onSelectionChange(): void {
  const selection = window.getSelection();
  if (!selection || selection.isCollapsed || selection.rangeCount === 0) {
    pendingRange = null;
    hideSelectionPill();
    send({ type: 'selectionCleared', v: DOC_PROTOCOL_VERSION });
    return;
  }
  const range = selection.getRangeAt(0);
  if (range.toString().trim().length === 0) return;
  pendingRange = range.cloneRange();
  // A selection competes with element hover for the same pointer; the drag
  // owns the interaction until it is released or cleared.
  hideHover();
  const rects = rectsOf(range);
  const last = rects[rects.length - 1];
  showSelectionPill(last);
  send({
    type: 'selection',
    v: DOC_PROTOCOL_VERSION,
    proposal: proposalForRange(range),
    rects,
    caret: last ?? { x: 0, y: 0, width: 0, height: 0 },
    // Dragging across text is not yet a request to comment on it: the shell
    // must not open a composer — or explain why it cannot — until the person
    // actually asks by pressing the pill.
    explicit: false,
  });
}

function showSelectionPill(near: DocRect | undefined): void {
  if (!near) return;
  selectionPill.style.left = `${near.x + near.width}px`;
  selectionPill.style.top = `${near.y + near.height + 8}px`;
  selectionPill.classList.add('is-visible');
}

function hideSelectionPill(): void {
  selectionPill.classList.remove('is-visible');
}

// ---------------------------------------------------------------------------
// Element inspection: hover outline + breadcrumb chip
//
// The model is the one people already know from element inspectors: point at
// something, see exactly what it is and what a comment would attach to, then
// click. Everything coarser than the thing under the cursor is one hop away on
// the chip's breadcrumb, so "the cell" and "the whole table" are both reachable
// without the cursor ever leaving the region it is pointing at.
// ---------------------------------------------------------------------------

/**
 * How long the chrome survives the cursor being over nothing.
 *
 * Without a grace period, any sliver of unresolvable space between an element
 * and the chip naming it tears the chip down mid-reach.
 */
const HOVER_GRACE_MS = 160;
/** Breadcrumb segments shown; deep trees truncate from the outside in. */
const BREADCRUMB_LIMIT = 4;
/**
 * How far the chip's hit box reaches DOWN over the element it names.
 *
 * The chip sits directly on the element's top edge, so the two boxes are
 * already contiguous and a cursor travelling between them crosses no unclaimed
 * row. This is only slack for sub-pixel rounding — and it is deliberately tiny,
 * because every pixel of it is a pixel of the element that answers to the chip
 * instead of to the document.
 */
const CHIP_OVERLAP = 2;

let hideTimer = 0;

/** Is this node part of the runtime's own UI rather than the document's? */
function isChrome(node: EventTarget | null): boolean {
  return node instanceof Node && layer.contains(node);
}

function cancelHide(): void {
  if (!hideTimer) return;
  clearTimeout(hideTimer);
  hideTimer = 0;
}

function scheduleHide(): void {
  if (hideTimer) return;
  hideTimer = setTimeout(() => {
    hideTimer = 0;
    hideHover();
  }, HOVER_GRACE_MS) as unknown as number;
}

function onPointerMove(event: MouseEvent): void {
  // A document that cannot take a comment gets no hover chrome at all. The
  // chip is opaque and clickable and is painted OVER the page, so showing it on
  // a document that is merely being read would occlude — and swallow clicks on
  // — a live page's own links, to offer an affordance that could only ever
  // answer "share this first". The selection pill remains the way to ask.
  if (!inspectEnabled) return;
  // THE SELF-HIDE BUG (attn-yqun.2): the runtime's own chrome is part of the
  // document it is annotating, so a cursor moving onto the chip is a mousemove
  // whose target resolves to no document scope. Treating that as "hovering
  // nothing" hid the chip out from under the cursor reaching for it, which made
  // it structurally unclickable. Chrome is never a hover subject.
  if (chip.contains(event.target as Node)) {
    cancelHide();
    return;
  }
  // Other chrome — a committed comment's pin, the selection pill — is not the
  // chip and must NOT hold it open: those hang outside the elements they belong
  // to, so resting on one used to cancel a pending hide that nothing re-armed,
  // stranding the chip on an element the cursor had long since left.
  if (isChrome(event.target)) return;
  // An active text selection owns the interaction; the two gestures must never
  // compete for the same drag.
  if (selectionIsLive()) {
    hideHover();
    return;
  }
  const target = event.target;
  if (!(target instanceof Element)) return;
  if (target === lastMoveTarget) {
    // Not a pure no-op: leaving the chip arms a hide, and the cursor may have
    // done nothing worse than clip the chip on its way back to the element it
    // was already on. Returning without disarming would time the chip out from
    // under a stationary cursor.
    if (hoverTarget) cancelHide();
    return;
  }
  lastMoveTarget = target;

  const chain = candidateChain(target);
  const block = defaultTarget(chain);
  if (!block) {
    scheduleHide();
    return;
  }
  cancelHide();
  if (block === hoverTarget) return;
  hoverTarget = block;
  outline(block);
  renderChip(publishScopeHover(chain));
}

function hideHover(): void {
  cancelHide();
  hoverTarget = null;
  lastMoveTarget = null;
  chip.classList.remove('is-visible');
  outline(undefined);
}

/**
 * Commit to the element the chip currently names.
 *
 * You comment on what the chip says you are commenting on — nothing else. That
 * is not a nicety, it is the safety rail: re-deriving a scope from the click
 * target instead let a click commit to an element that was never outlined or
 * named. The reachable case was mundane — drag-select a sentence to read it,
 * then click elsewhere to dismiss the selection. The chrome was hidden for the
 * whole gesture (a live selection suppresses it), yet by click time mousedown
 * had already collapsed the selection, so the guard here saw nothing and a
 * composer opened on whatever happened to be under the pointer.
 *
 * Requiring a visible chip also means a click can only ever be swallowed while
 * the person can SEE what it will attach to.
 */
function onDocumentClick(event: MouseEvent): void {
  if (isChrome(event.target)) return;
  if (!inspectEnabled) return;
  const target = event.target;
  if (!(target instanceof Element)) return;
  const scopeId = currentScopeId;
  const named = hoverTarget;
  // No chip on screen (hidden by a selection, timed out, never raised) means
  // nothing was offered, so nothing is taken: the click belongs to the page.
  if (!scopeId || !named) return;
  // The click must land on the very thing the chip names. A pin or overlay can
  // sit over a neighbour, and the pointer can outrun the hover.
  if (named !== target && !named.contains(target)) return;
  event.preventDefault();
  event.stopPropagation();
  pickScope(scopeId);
}

function publishScopeHover(chain: Element[]): ScopeCandidate[] {
  scopeElements.clear();
  const candidates: ScopeCandidate[] = chain.slice(0, 8).map((el) => {
    const scopeId = `scope-${(scopeSeq += 1)}`;
    scopeElements.set(scopeId, el);
    const preview = scopePreview(el);
    return {
      scopeId,
      title: scopeTitle(el),
      // The row/cell branches assemble from full cell text; the parser drops
      // any candidate whose preview exceeds 256 BYTES, so bound at the wire.
      preview: preview === null ? null : clampText(preview, 200, 256),
      selector: anchorForElement(root, el, '').cssSelector,
      commentCount: commentsOn(el),
      rects: rectsOf(el),
    };
  });
  send({ type: 'scopeHover', v: DOC_PROTOCOL_VERSION, chain: candidates });
  return candidates;
}

/**
 * Render the label for the current hover: `table › row 2 › cell`.
 *
 * Outermost first so the breadcrumb reads the way a path does, with the thing
 * actually under the cursor last and marked current.
 */
function renderChip(candidates: ScopeCandidate[]): void {
  chipBody.textContent = '';
  currentScopeId = candidates[0]?.scopeId ?? null;
  if (candidates.length === 0) {
    chip.classList.remove('is-visible');
    return;
  }
  // `candidates` is innermost-first (the wire order the shell expects); the
  // breadcrumb reads the other way.
  const shown = candidates.slice(0, BREADCRUMB_LIMIT).reverse();
  const truncated = candidates.length > BREADCRUMB_LIMIT;
  if (truncated) {
    const ellipsis = document.createElement('span');
    ellipsis.className = 'attn-chip-sep';
    ellipsis.textContent = '…';
    chipBody.appendChild(ellipsis);
  }
  shown.forEach((candidate, index) => {
    if (index > 0 || truncated) {
      const separator = document.createElement('span');
      separator.className = 'attn-chip-sep';
      separator.textContent = '›';
      separator.setAttribute('aria-hidden', 'true');
      chipBody.appendChild(separator);
    }
    const current = index === shown.length - 1;
    const segment = document.createElement('button');
    segment.type = 'button';
    segment.className = 'attn-chip-seg';
    if (current) segment.classList.add('is-current');
    segment.dataset.scope = candidate.scopeId;
    segment.setAttribute(
      'aria-label',
      `Comment on ${candidate.preview ?? candidate.title}`,
    );

    const title = document.createElement('span');
    title.className = 'attn-chip-title';
    title.textContent = candidate.title;
    segment.appendChild(title);

    // Only the current segment carries content: the breadcrumb is for aiming,
    // and repeating every ancestor's text would bury the thing being named.
    if (current && candidate.preview && candidate.preview !== candidate.title) {
      const preview = document.createElement('span');
      preview.className = 'attn-chip-preview';
      preview.textContent = clampText(candidate.preview, 48, 192);
      segment.appendChild(preview);
    }
    if (candidate.commentCount > 0) {
      const badge = document.createElement('span');
      badge.className = 'attn-chip-count';
      badge.textContent = String(candidate.commentCount);
      segment.appendChild(badge);
    }

    segment.addEventListener('mouseenter', () => outline(scopeElements.get(candidate.scopeId)));
    segment.addEventListener('mouseleave', () => outline(hoverTarget ?? undefined));
    // Same reason the selection pill does it: a mousedown here would collapse
    // any live selection and can begin one in the document underneath, so the
    // press must not reach the page at all — only the click that follows it
    // means anything.
    segment.addEventListener('mousedown', (event) => event.preventDefault());
    segment.addEventListener('click', (event) => {
      event.preventDefault();
      event.stopPropagation();
      pickScope(candidate.scopeId);
    });
    chipBody.appendChild(segment);
  });

  chip.classList.add('is-visible');
  if (hoverTarget) positionChip(hoverTarget);
}

function positionChip(el: Element): void {
  const rect = el.getBoundingClientRect();
  const top = rect.top + window.scrollY;
  const left = rect.left + window.scrollX;
  // Measured, not assumed: the chip's height depends on the host document's
  // font metrics, and a stale guess would leave the gap this positioning
  // exists to close.
  const height = chip.offsetHeight;
  // The chip's hit box overlaps the element's top edge (see the transparent
  // bottom padding in RUNTIME_STYLES) so a cursor travelling from the element
  // to the chip never crosses unclaimed space. Documents that start at the very
  // top have nowhere above to put it, so it tucks just inside instead.
  const above = top - height + CHIP_OVERLAP;
  chip.style.top = `${above < window.scrollY ? top : above}px`;
  // Clamped at BOTH edges. The layer is absolutely positioned in the document,
  // so a chip overhanging the right edge widens `scrollWidth` and raises a
  // horizontal scrollbar on a document that never had one — hovering the last
  // cell of a wide table was enough.
  const widest = document.documentElement.clientWidth - chip.offsetWidth - 2;
  chip.style.left = `${Math.max(Math.min(left, window.scrollX + Math.max(widest, 0)), 2)}px`;
}

let outlineEl: HTMLElement | null = null;

function outline(el: Element | undefined): void {
  if (!el) {
    outlineEl?.remove();
    outlineEl = null;
    return;
  }
  const rect = el.getBoundingClientRect();
  const box = outlineEl ?? document.createElement('div');
  box.className = 'attn-outline';
  box.style.cssText = `top:${rect.top + window.scrollY}px;left:${rect.left + window.scrollX}px;width:${rect.width}px;height:${rect.height}px`;
  if (!outlineEl) layer.appendChild(box);
  outlineEl = box;
}

function pickScope(scopeId: string): void {
  const el = scopeElements.get(scopeId);
  if (!el) return;
  hideHover();
  send({
    type: 'scopePicked',
    v: DOC_PROTOCOL_VERSION,
    proposal: proposalForElement(el),
    rects: rectsOf(el),
    // Picking a scope is only ever a deliberate act — a chip press, a click in
    // inspect mode, or the shell replaying one. The shell owes an answer.
    explicit: true,
  });
}

