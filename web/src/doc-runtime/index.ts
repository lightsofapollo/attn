const HIGHLIGHT_BUCKET = 'attn-text';
const HIGHLIGHT_ACTIVE_BUCKET = 'attn-text-active';
/** Context captured either side of a selection, for later disambiguation. */
const CONTEXT_CHARS = 64;

interface LiveAnchor {
  spec: RenderableAnchor;
  range: Range | null;
  element: Element | null;
  status: AnchorResolution['status'];
  confidence: number;
  overlay: HTMLElement | null;
  pin: HTMLElement | null;
}

let port: MessagePort | null = null;
let root: HTMLElement;
let layer: HTMLElement;
/** Hover affordance: the breadcrumb label naming what a click would anchor to. */
let chip: HTMLElement;
let chipBody: HTMLElement;
let selectionPill: HTMLButtonElement;

const anchors = new Map<string, LiveAnchor>();
/** Scope candidates offered in the current hover, keyed by their scopeId. */
const scopeElements = new Map<string, Element>();
/** Innermost element the chip currently names; what a plain click anchors to. */
let hoverTarget: Element | null = null;
/** Scope id of the chip's current segment, so the whole chip is pressable. */
let currentScopeId: string | null = null;
/** Last `mousemove` target, to skip re-resolving the same element every pixel. */
let lastMoveTarget: Element | null = null;
let pendingRange: Range | null = null;
let scopeSeq = 0;
/**
 * Whether a click on the document body commits to a comment.
 *
 * Off until the shell says otherwise. Hover chrome is always live — the point
 * of the redesign is that the annotation model is *visible* — but swallowing
 * every click is only defensible once the document is genuinely under review.
 * An unshared page keeps its links, buttons and form fields working, and the
 * chip is the affordance that still offers to comment.
 */
let inspectEnabled = false;

// ---------------------------------------------------------------------------
// Transport
// ---------------------------------------------------------------------------

function send(message: DocMessage): void {
  port?.postMessage(message);
}

function toDocRect(rect: DOMRect): DocRect {
  return { x: rect.x, y: rect.y, width: rect.width, height: rect.height };
}

/** Merge the many client rects of a multi-line range into per-line bands. */
function rectsOf(target: Range | Element | null): DocRect[] {
  if (!target) return [];
  const list = Array.from(target.getClientRects()).filter(
    (r) => r.width > 0 && r.height > 0,
  );
  return list.slice(0, 128).map(toDocRect);
}

// ---------------------------------------------------------------------------
// Scope chain (validated by planning/collab/prototypes/html-annotation.html)
// ---------------------------------------------------------------------------

/**
 * Structural scopes a comment may anchor to, finest to coarsest.
 *
 * Broader than a prose-block list because the model is now element-first: you
 * point at a thing in the page and comment on *that thing*, so a figure, a
 * button and a section all have to be nameable. Anything outside the set still
 * resolves — {@link fallbackScope} climbs to the nearest laid-out ancestor —
 * so no part of a document is un-commentable.
 */
const SCOPE_TAGS = new Set([
  'TD', 'TH', 'TR', 'LI', 'FIGURE', 'PRE', 'CODE', 'TABLE', 'BLOCKQUOTE',
  'H1', 'H2', 'H3', 'H4', 'H5', 'H6', 'P', 'IMG', 'FIGCAPTION', 'UL', 'OL',
  'DL', 'DT', 'DD', 'SECTION', 'ARTICLE', 'ASIDE', 'HEADER', 'FOOTER', 'MAIN',
  'NAV', 'DETAILS', 'SUMMARY', 'FORM', 'VIDEO', 'AUDIO', 'CANVAS', 'SVG',
  'A', 'BUTTON', 'LABEL', 'INPUT', 'TEXTAREA', 'SELECT', 'HR',
]);

const isCell = (el: Element): boolean => el.tagName === 'TD' || el.tagName === 'TH';

/**
 * The nearest ancestor that actually occupies space.
 *
 * Div-soup documents (and anything generated by a layout framework) can nest a
 * hovered node many levels below the closest recognised scope. Falling back to
 * whatever box the cursor is genuinely over keeps every pixel of every document
 * commentable, which is the promise the hover outline makes.
 */
function fallbackScope(el: Element): Element | null {
  let cursor: Element | null = el;
  for (let depth = 0; cursor && cursor !== root && depth < 12; depth += 1) {
    const rect = cursor.getBoundingClientRect();
    if (rect.width > 0 && rect.height > 0) return cursor;
    cursor = cursor.parentElement;
  }
  return null;
}

function candidateChain(el: Element): Element[] {
  const chain: Element[] = [];
  let cursor: Element | null = el;
  while (cursor && cursor !== root && chain.length < 12) {
    // Upper-cased, not compared raw: HTML elements report an upper-case
    // `tagName` but SVG (a different namespace) preserves its case, so an
    // `<svg>` chart silently missed the list and fell through to the fallback.
    if (SCOPE_TAGS.has(cursor.tagName.toUpperCase())) chain.push(cursor);
    cursor = cursor.parentElement;
  }
  if (chain.length === 0) {
    const fallback = fallbackScope(el);
    if (fallback) chain.push(fallback);
  }
  return chain;
}

/**
 * What a plain click anchors to: the innermost thing under the cursor.
 *
 * This is the direct-manipulation contract — you comment on what you pointed
 * at. Coarser scopes stay one click away on the chip's breadcrumb, which is
 * where "actually, the whole row" belongs.
 */
function defaultTarget(chain: Element[]): Element | undefined {
  return chain[0];
}

function rowIndexOf(tr: Element): number {
  const section = tr.parentElement;
  if (!section) return 1;
  return Array.from(section.children).filter((c) => c.tagName === 'TR').indexOf(tr) + 1;
}

function scopeTitle(el: Element): string {
  if (isCell(el)) return 'cell';
  if (el.tagName === 'TR') return el.closest('thead') ? 'header row' : `row ${rowIndexOf(el)}`;
  if (el.tagName === 'LI') return 'list item';
  if (el.tagName === 'PRE') return 'code block';
  if (el.tagName === 'UL' || el.tagName === 'OL') return 'list';
  if (el.tagName === 'A') return 'link';
  if (el.tagName === 'IMG') return 'image';
  if (el.tagName === 'BLOCKQUOTE') return 'quote';
  if (/^H[1-6]$/.test(el.tagName)) return 'heading';
  return el.tagName.toLowerCase();
}

function scopePreview(el: Element): string | null {
  if (el.tagName === 'TR') {
    const cells = Array.from(el.querySelectorAll('th,td')).map((c) => c.textContent?.trim() ?? '');
    const label = el.closest('thead') ? 'header row' : `row ${rowIndexOf(el)}`;
    const rest = [cells[0], cells[1]].filter(Boolean).join(' · ');
    return rest ? `${label} · ${rest}` : label;
  }
  if (isCell(el)) {
    const tr = el.closest('tr');
    const column = tr ? Array.from(tr.children).indexOf(el) : -1;
    const headerRow = el.closest('table')?.querySelector('thead tr');
    const columnName = headerRow?.children[column]?.textContent?.trim();
    const value = el.textContent?.trim() ?? '';
    return columnName ? `${columnName}: ${value}` : value;
  }
  const text = el.textContent?.trim() ?? '';
  return text ? text.slice(0, 80) : null;
}

function commentsOn(el: Element): number {
  let count = 0;
  for (const anchor of anchors.values()) {
    if (anchor.element === el) count += 1;
  }
  return count;
}

// ---------------------------------------------------------------------------
// Proposals
// ---------------------------------------------------------------------------

/**
 * Text immediately before and after *this* range.
 *
 * Derived from the range itself rather than by searching the document for the
 * quote: a search finds the first occurrence, which is the wrong one precisely
 * when the text repeats — the case prefix/suffix exist to disambiguate.
 */
function contextAround(range: Range): { prefix: string; suffix: string } {
  const before = root.ownerDocument.createRange();
  before.selectNodeContents(root);
  before.setEnd(range.startContainer, range.startOffset);

  const after = root.ownerDocument.createRange();
  after.selectNodeContents(root);
  after.setStart(range.endContainer, range.endOffset);

  // Code-unit slices can split a surrogate pair at the cut, leaving a lone
  // half that round-trips as U+FFFD and never matches the document again.
  // Trim to a generous code-unit window first (a spread of the whole document
  // text would be O(doc) per selection), then cut by code points.
  const beforeText = before.toString();
  const prefixCps = [...beforeText.slice(-CONTEXT_CHARS * 2)].slice(-CONTEXT_CHARS);
  const suffixCps = [...after.toString().slice(0, CONTEXT_CHARS * 2)].slice(0, CONTEXT_CHARS);
  if (prefixCps.length > 0 && beforeText.length > CONTEXT_CHARS * 2) {
    // The code-unit pre-cut itself may have split a pair at the window's
    // leading edge; a lone low surrogate there is noise, not context.
    const first = prefixCps[0].charCodeAt(0);
    if (first >= 0xdc00 && first <= 0xdfff) prefixCps.shift();
  }
  return {
    prefix: prefixCps.join(''),
    suffix: suffixCps.join(''),
  };
}

function proposalForRange(range: Range): AnchorProposal {
  const startOffset = textOffsetOf(root, range.startContainer, range.startOffset);
  const endOffset = textOffsetOf(root, range.endContainer, range.endOffset);
  const quote = range.toString();
  const { prefix, suffix } = contextAround(range);
  return {
    html: anchorForRange(root, range),
    // Parser + Rust cap: 4096 BYTES; a character slice overruns it 4× on CJK.
    quote: clampText(quote, 4000, 4096),
    prefix,
    suffix,
    textStart: startOffset,
    textEnd: endOffset,
  };
}

function proposalForElement(el: Element): AnchorProposal {
  const preview = scopePreview(el) ?? scopeTitle(el);
  const html = anchorForElement(root, el, preview);
  const quote = clampText((el.textContent ?? '').trim(), 4000, 4096);
  return {
    html,
    quote,
    prefix: '',
    suffix: '',
    textStart: html.textPosition?.start ?? 0,
    textEnd: html.textPosition?.end ?? 0,
  };
}

