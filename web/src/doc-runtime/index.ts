function handleShellMessage(message: ShellMessage): void {
  switch (message.type) {
    case 'renderAnchors':
      renderAnchors(message.anchors);
      break;
    case 'setAnchorState':
      setAnchorState(message.anchorId, message.state);
      break;
    case 'focusAnchor':
      focusAnchor(message.anchorId, message.scrollIntoView);
      break;
    case 'pickScope':
      pickScope(message.scopeId);
      break;
    case 'dismissSelection':
      window.getSelection()?.removeAllRanges();
      pendingRange = null;
      hideSelectionPill();
      break;
    case 'inspect': {
      const enabled = message.enabled === true;
      // Turning inspection off has to take DOWN the chrome already on screen,
      // not merely stop raising more. A stopped or revoked room leaves a
      // visible chip whose own click handler bypasses `onDocumentClick` — so it
      // would go on swallowing page clicks and emitting proposals for a
      // document that is no longer reviewable.
      if (inspectEnabled && !enabled) {
        hideHover();
        currentScopeId = null;
      }
      inspectEnabled = enabled;
      break;
    }
    case 'theme':
      root.dataset.attnTheme = message.mode;
      break;
    default:
      break;
  }
}

function mountChrome(): void {
  const style = document.createElement('style');
  style.textContent = RUNTIME_STYLES;
  document.head.appendChild(style);

  layer = document.createElement('div');
  layer.className = 'attn-layer';
  document.body.appendChild(layer);

  chip = document.createElement('div');
  chip.className = 'attn-chip';
  chip.setAttribute('role', 'toolbar');
  chip.setAttribute('aria-label', 'Comment on this element');
  // Entering the chip is the one gesture the grace period exists to protect.
  chip.addEventListener('mouseenter', cancelHide);
  chip.addEventListener('mouseleave', scheduleHide);
  // The whole chip is pressable, not just its segments. Its reach corridor and
  // its padding sit ON TOP of the document, so a click there can never fall
  // through to the page — leaving a strip that did nothing at all: no comment,
  // no page interaction. A press anywhere on a label that names something means
  // "comment on that thing".
  chip.addEventListener('mousedown', (event) => event.preventDefault());
  chip.addEventListener('click', (event) => {
    const target = event.target;
    // Segments carry their own scope and handle themselves.
    if (target instanceof Element && target.closest('.attn-chip-seg')) return;
    event.preventDefault();
    event.stopPropagation();
    if (currentScopeId) pickScope(currentScopeId);
  });
  chipBody = document.createElement('div');
  chipBody.className = 'attn-chip-body';
  chip.appendChild(chipBody);
  layer.appendChild(chip);

  selectionPill = document.createElement('button');
  selectionPill.type = 'button';
  selectionPill.className = 'attn-pill';
  selectionPill.textContent = 'Comment';
  // mousedown would collapse the selection before the click lands.
  selectionPill.addEventListener('mousedown', (event) => event.preventDefault());
  selectionPill.addEventListener('click', (event) => {
    event.preventDefault();
    event.stopPropagation();
    if (!pendingRange) return;
    const rects = rectsOf(pendingRange);
    send({
      type: 'selection',
      v: DOC_PROTOCOL_VERSION,
      proposal: proposalForRange(pendingRange),
      rects,
      caret: rects[rects.length - 1] ?? { x: 0, y: 0, width: 0, height: 0 },
      // The person asked. Whatever the shell decides, it must say so.
      explicit: true,
    });
  });
  layer.appendChild(selectionPill);
}

function attachPort(candidate: MessagePort): void {
  port = candidate;
  port.onmessage = (event: MessageEvent) => {
    // The port is private, but the document's own scripts share this context
    // and could reach it, so shape is still checked before use.
    const data = event.data as ShellMessage | undefined;
    if (!data || typeof data !== 'object' || typeof data.type !== 'string') return;
    if (data.v !== DOC_PROTOCOL_VERSION) return;
    handleShellMessage(data);
  };
  port.start();

  send({
    type: 'ready',
    v: DOC_PROTOCOL_VERSION,
    textLength: documentText(root).length,
    title: clampText(document.title, 200, 512),
  });
}

function boot(): void {
  // A document saved after injection ("Save page as…" of a reviewed doc,
  // then re-shared) already carries a copy of this runtime. Two instances
  // would both answer the handshake and fight over the port — the loser's
  // empty geometry reports would flap the shell's rail every scroll. Both
  // copies share this window, so a global is a reliable mutex.
  const guard = window as Window & { __attnDocRuntime?: boolean };
  if (guard.__attnDocRuntime) return;
  guard.__attnDocRuntime = true;

  root = document.body;
  mountChrome();

  document.addEventListener('selectionchange', onSelectionChange);
  document.addEventListener('mousemove', onPointerMove, { passive: true });
  // Capture phase: in inspect mode the click has to be taken before any of the
  // document's own handlers see it, or a link navigates the frame away from the
  // thing the person was commenting on. Not passive — it calls preventDefault.
  document.addEventListener('click', onDocumentClick, true);
  // Leaving the document entirely is unambiguous; no grace period needed.
  document.documentElement.addEventListener('mouseleave', hideHover);
  window.addEventListener('scroll', scheduleReflow, { passive: true });
  window.addEventListener('resize', scheduleReflow, { passive: true });
  new ResizeObserver(scheduleReflow).observe(document.body);

  window.addEventListener('message', (event: MessageEvent) => {
    // Origin is always "null" for an opaque frame, so it carries no information.
    // The shell is identified by being our parent; the port it hands over is
    // what makes every later message trustworthy.
    if (event.source !== window.parent) return;
    const data = event.data as { type?: unknown } | undefined;
    if (!data || data.type !== SHELL_INIT) return;
    const [candidate] = event.ports;
    if (candidate) attachPort(candidate);
  });

  window.parent.postMessage({ type: DOC_HELLO, v: DOC_PROTOCOL_VERSION }, '*');
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', boot, { once: true });
} else {
  boot();
}
